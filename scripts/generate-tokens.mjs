// Canonical catalog -> checked-in Rust. Run with --check to detect drift.
import fs from 'node:fs';
const root = new URL('../', import.meta.url);
const doc = JSON.parse(fs.readFileSync(new URL('src/design_tokens.json', root)));
const ident = s => s.split(/[.\-]/).map(x => x[0].toUpperCase()+x.slice(1)).join('');
const roles = Object.entries(doc.color.semantic);
let out = '// Generated by scripts/generate-tokens.mjs; do not edit.\n';
out += '#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n#[repr(usize)]\npub enum Role {\n' + roles.map(([k])=>'    '+ident(k)+',').join('\n')+'\n}\n';
out += 'pub const ROLE_NAMES: &[&str] = &['+roles.map(([k])=>JSON.stringify(k)).join(',')+'];\n';
for (const id of doc.targetThemes) {
 out += 'pub const '+id.toUpperCase()+': [u32; '+roles.length+'] = [\n';
 for (const [role,alias] of roles) {
  const key = alias.match(/^\{color\.primitive\.\$theme\.(.+)\}$/)?.[1];
  const hex = doc.color.primitive[id][key];
  if (!/^#[a-f0-9]{6}([a-f0-9]{2})?$/i.test(hex)) throw new Error(id+': '+role);
  out += '    0x'+hex.slice(1).toLowerCase()+', // '+role+'\n';
 }
 out += '];\n';
}
function geometry(value, keys=[]) {
 for (const [key,v] of Object.entries(value)) {
  if (typeof v === 'number') out += 'pub const '+keys.concat(key).join('_').replace(/([a-z])([A-Z])/g,'$1_$2').toUpperCase()+': f32 = '+v.toFixed(1)+';\n';
  else if (v && !Array.isArray(v) && typeof v==='object') geometry(v,keys.concat(key));
 }
}
out += 'pub mod geometry {\n'; geometry(doc.size,['size']); geometry(doc.layer,['layer']); out += '}\n';
const target = new URL('src/design_tokens.rs',root);
if ((typeof process !== 'undefined' && process.argv.includes('--check')) || globalThis.GITCRAB_CHECK_TOKENS) {
 if (fs.readFileSync(target,'utf8').replace(/\r\n/g, '\n') !== out) { throw new Error('Token output drift; run node scripts/generate-tokens.mjs'); }
} else fs.writeFileSync(target,out);
